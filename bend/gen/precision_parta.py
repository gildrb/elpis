"""Emit bend/precision_parta.bend from the partA decode table.

Input: bend/gen/precision_parta.txt (or --table PATH). It is the unchanged stdout of
analyze_a.py, a CPU-only script of the Int8Linear precision work. analyze_a.py is not
in the repository: it reads the persisted coop autotune cache of the served containers
(coop_autotune_v1.bin, a binary file that the stock autotuner wrote on the GPU) and the
cuobjdump -res-usage text of the built exllamav3_ext library. Neither input is in the
repository.
Output: the Bend source, on stdout.

The script reads the "stock fp16 run (k-values)" column. For each op, all m = 1..8 must
have one class, or an int8 class for m <= t and one other class for m > t. Other
shapes stop the script. lm_head's entry is a fixed placeholder (Ord.Fp32{}).
The p32 flag of each op (fp32 partials between thread blocks) is not in the table. OPS
states it: the C dtype of the sliced exl3_mgemm (the stock kernel column, checked), True
for the QTIP GEMV (fp32 partials), and False for the MLP gate / up tensor-core GEMM
(fp16 C, blocks split columns). Law stock_table_partA checks the result.

Regenerate and check the tracked file (from the repository root):
    python3 -I -B bend/gen/precision_parta.py > /tmp/x && cmp /tmp/x bend/precision_parta.bend
"""

import argparse
import re
from pathlib import Path
from typing import NoReturn

ROOT = Path(__file__).resolve().parents[2]
TABLE_HEAD = [
    "| op | m | stock kernel | stock config | stock fp16 run (k-values) | elpis kernel | elpis run |",
    "|---|---|---|---|---|---|---|",
]
# (table op label, S.Op constructor, p32), in the declaration order of S.Op.
OPS = [
    ("attn q_proj (q|gate)", "AttnQG", False),
    ("attn k_proj", "AttnK", False),
    ("attn v_proj", "AttnV", False),
    ("attn o_proj", "AttnO", True),
    ("GDN in_proj_qkv", "GdnQkv", True),
    ("GDN in_proj_z", "GdnZ", True),
    ("GDN out_proj", "GdnOut", True),
    ("MLP gate_proj", "MlpGate", False),
    ("MLP up_proj", "MlpUp", False),
    ("MLP down_proj", "MlpDown", True),
    ("lm_head", "LmHead", None),
]
HEAD = """\
# The decode table of bend/gen/precision_parta.txt (the partA table that analyze_a.py printed over the
# stock sources and the persisted autotune cache), generated by bend/gen/precision_parta.py: the stock
# class of every served (op, m), in k-values.
# lm_head's entry is a placeholder (never used: law stock_table_partA excludes it through not_head).
# Used by bend/precision_laws.bend (law stock_table_partA) and printed by bend/PRECISION_TABLE.bend.
import Base
import ./precision_order.bend as Ord
import ./precision_stock.bend as S

def part_a(op: S.Op, +m: Nat) -> Ord.Acc:
  match op:
"""


def fail(message: str) -> NoReturn:
    """Stop with an error."""
    raise SystemExit(f"precision_parta: FAIL: {message}")


def rows(path: Path) -> dict[str, dict[int, list[str]]]:
    """Read the table: op label -> m -> the seven cells."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if lines[:2] != TABLE_HEAD:
        fail(f"{path}: the table header is not analyze_a.py's")
    out: dict[str, dict[int, list[str]]] = {}
    for line in lines[2:]:
        if not (line.startswith("| ") and line.endswith(" |")):
            fail(f"{path}: not a table row: {line!r}")
        cells = line[2:-2].split(" | ")
        if len(cells) != 7 or not cells[1].isdigit():
            fail(f"{path}: bad row: {line!r}")
        by_m = out.setdefault(cells[0], {})
        if int(cells[1]) in by_m:
            fail(f"{path}: duplicate row: {line!r}")
        by_m[int(cells[1])] = cells
    if sorted(out) != sorted(label for label, _, _ in OPS):
        fail(f"{path}: the ops are not {[label for label, _, _ in OPS]}")
    for label, by_m in out.items():
        if sorted(by_m) != list(range(1, 9)):
            fail(f"{path}: {label}: the rows are not m = 1..8")
    return out


def acc(cells: list[str], p32: bool) -> str:
    """The Ord.Acc term of one row."""
    kernel, run = cells[2], cells[4]
    found = re.search(r"fp32 out (True|False)\)", kernel)
    if found and (found.group(1) == "True") != p32:
        fail(f"{cells[0]} m {cells[1]}: p32 {p32} disagrees with {kernel!r}")
    if kernel.startswith("exl3_gemv_kernel ") and not p32:
        fail(f"{cells[0]} m {cells[1]}: the QTIP GEMV keeps fp32 partials")
    if run == "int8 (no fp16 run)":
        return "Ord.Int8{}"
    span = re.fullmatch(r"(\d+)(?:\.\.(\d+))?", run)
    if span is None:
        fail(f"{cells[0]} m {cells[1]}: no static stock run: {run!r}")
    lo = span.group(1)
    hi = span.group(2) or lo
    return f"Ord.Runs{{{lo}n, {hi}n, {p32}{{}}}}"


def entry(by_m: dict[int, list[str]], p32: bool | None) -> tuple[int, str]:
    """(order key, Bend term) of one op: 0 one class, 1 int8 then one class, 2 placeholder."""
    if p32 is None:
        return 2, "Ord.Fp32{}"
    classes = [acc(by_m[m], p32) for m in range(1, 9)]
    first = classes[0]
    if all(c == first for c in classes):
        return 0, first
    t = next(i for i, c in enumerate(classes) if c != first)
    rest = classes[t]
    if first != "Ord.Int8{}" or any(c != rest for c in classes[t:]):
        fail(
            f"{by_m[1][0]}: the classes over m are not int8 for m <= t, then one class"
        )
    return 1, f"S.acc_pick(Nat.is_le(m, {t}n), {first}, {rest})"


def main() -> None:
    """Print bend/precision_parta.bend."""
    parser = argparse.ArgumentParser(
        description="Emit bend/precision_parta.bend on stdout."
    )
    parser.add_argument(
        "--table",
        type=Path,
        default=ROOT / "bend/gen/precision_parta.txt",
        help="analyze_a.py stdout (default: bend/gen/precision_parta.txt)",
    )
    table = rows(parser.parse_args().table)
    entries = [(entry(table[label], p32), ctor) for label, ctor, p32 in OPS]
    entries.sort(key=lambda e: e[0][0])
    out = [HEAD]
    for (_, term), ctor in entries:
        out.append(f"    case S.{ctor}{{}}:\n      {term}\n")
    out.append("\ndef not_head(op: S.Op) -> Bool:\n  match op:\n")
    out.append("    case S.LmHead{}:\n      False{}\n")
    for _, ctor, p32 in OPS:
        if p32 is not None:
            out.append(f"    case S.{ctor}{{}}:\n      True{{}}\n")
    print("".join(out), end="")


if __name__ == "__main__":
    main()
